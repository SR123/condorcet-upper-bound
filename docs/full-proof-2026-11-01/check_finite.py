def refine(front, groups):
    for g in groups:
        front = {d & m for d in front for m in g}
        front.discard(0)
    return front

def canonical6(d):
    orders = [P[6][i] for i in bits(d)]
    images = []
    for p in orders:
        inv = [p.index(a) for a in range(6)]
        images.append(sum(1 << IX[6][tuple(inv[a] for a in q)]
                          for q in orders))
    return min(images)

