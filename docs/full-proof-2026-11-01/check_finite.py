def bits(d):
    while d:
        b = d & -d
        yield b.bit_length() - 1
        d -= b

P = {n: list(permutations(range(n))) for n in (5, 6, 7)}
IX = {n: {p: i for i, p in enumerate(P[n])} for n in P}

def norm(p):
    r = {a: i for i, a in enumerate(sorted(p))}
    return tuple(r[a] for a in p)

def swap(p, j):
    return p[:j] + (p[j+1], p[j]) + p[j+2:]

def masks(n):
    full = (1 << factorial(n)) - 1
    groups = []
    for t in combinations(range(n), 3):
        traces = [tuple(a for a in p if a in t) for p in P[n]]
        opts = [sum(1 << i for i, q in enumerate(traces)
                    if q[r] != a) for a in t for r in (0, 2)]
        groups.append((n-1 in t, opts))
    for a, b in combinations(range(n), 2):
        m = sum(1 << i for i, p in enumerate(P[n])
                if p.index(a) < p.index(b))
        groups.append((b == n-1, [full, m, full ^ m]))
    return full, groups

