def slices(n, d):
    bottom = [0] * n
    for i in bits(d):
        bottom[LAST[n][i]] |= 1 << LEFT[n][i]
    width = factorial(n-1)
    m = (1 << width) - 1
    top = [(d >> (width*x)) & m for x in range(n)]
    return bottom, top

